describe('src/components', () => {
  const dir = join(ROOT, 'src', 'components');

  it('holds only the atomic layers and ui/', () => {
    const stray = names(dir).filter((n) => !LAYERS.includes(n));
    expect(stray, `src/components: not a layer: ${stray.join(', ')}`).toEqual([]);
  });

  it('every layer entry is <Name>/ with <Name>.tsx, index.ts, <Name>.stories.tsx and __tests__/<Name>.test.tsx', () => {
    for (const layer of LAYERS.filter((l) => l !== 'ui')) {
      for (const name of names(join(dir, layer))) {
        const folder = join(dir, layer, name);
        expect(
          isDir(folder) && PASCAL.test(name),
          `src/components/${layer}/${name}: a PascalCase folder`,
        ).toBe(true);
        const allowed = [
          `${name}.tsx`,
          'index.ts',
          `${name}.stories.tsx`,
          `${name}.variants.ts`,
          TESTS_DIR,
        ];
        if (layer === 'atoms' && name === 'Icon') allowed.push('registry.json');
        const stray = names(folder).filter((n) => !allowed.includes(n));
        expect(
          stray,
          `src/components/${layer}/${name}: not in the component shape: ${stray.join(', ')}`,
        ).toEqual([]);
        for (const required of [
          `${name}.tsx`,
          'index.ts',
          `${name}.stories.tsx`,
          join(TESTS_DIR, `${name}.test.tsx`),
        ]) {
          expect(
            existsSync(join(folder, required)),
            `src/components/${layer}/${name}: missing ${posix(required)}`,
          ).toBe(true);
        }
        const notTests = names(join(folder, TESTS_DIR)).filter((n) => !/\.test\.tsx?$/.test(n));
        expect(
          notTests,
          `src/components/${layer}/${name}/__tests__ holds only tests: ${notTests.join(', ')}`,
        ).toEqual([]);
      }
    }
  });

  it('ui/ primitives match .manifest.json byte for byte (regenerate with `corepack yarn ui:add <name>`, never edit)', () => {
    const ui = join(dir, 'ui');
    const manifest = readJson(join(ui, '.manifest.json')) as Record<string, string>;
    const files = names(ui).filter((n) => n.endsWith('.tsx'));
    expect(
      Object.keys(manifest).sort(),
      'ui/ files and manifest entries differ — regenerate with `corepack yarn ui:add <name>`, never edit',
    ).toEqual(files);
    for (const f of files) {
      expect(
        sha256(join(ui, f)),
        `src/components/ui/${f} differs from .manifest.json — regenerate with \`corepack yarn ui:add ${f.slice(0, -4)}\`, never edit`,
      ).toBe(manifest[f]);
    }
  });
});

