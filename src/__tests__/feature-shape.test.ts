/**
 * Comments removed, LINE COUNT PRESERVED: a block comment becomes the same number of blank lines.
 * Clauses that report a line number, or read the lines above a match, compare the stripped index
 * against the RAW file — collapsing a block comment shifted every line after it. Latent until
 * plan 03.1-06 put the first `useEffect` under `src/lib/hooks/`, which until then was reserved,
 * so the effect-comment clause had never had a subject to get wrong.
 */
const stripComments = (code: string): string =>
  code
    .replace(/\/\*[\s\S]*?\*\//g, (m) => '\n'.repeat((m.match(/\n/g) ?? []).length))
    .replace(/(^|[^:'"`])\/\/.*$/gm, '$1');
const sha256 = (abs: string): string =>
  createHash('sha256').update(readFileSync(abs)).digest('hex');
const PASCAL = /^[A-Z][A-Za-z0-9]*$/;
const KEBAB_TS = /^[a-z0-9]+([.-][a-z0-9]+)*\.ts$/;

interface Leaf {
  readonly path: string;
  readonly value: unknown;
}
const leaves = (value: unknown, prefix = ''): Leaf[] =>
  typeof value === 'object' && value !== null && !Array.isArray(value)
    ? Object.entries(value).flatMap(([k, v]) => leaves(v, prefix === '' ? k : `${prefix}.${k}`))
    : [{ path: prefix, value }];
const readJson = (abs: string): unknown => JSON.parse(read(abs));
const quoted = (key: string): RegExp =>
  new RegExp(`['"\`]${key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"\`]`);
const dynamicNamespace = (ns: string): RegExp =>
  new RegExp(`\`${ns.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\.\\$\\{`);
/** A leaf `a.b.c` counts as referenced when quoted in full or when an ancestor namespace is built dynamically. */
const isReferenced = (leafPath: string, code: string): boolean => {
  if (quoted(leafPath).test(code)) return true;
  // A feature's own `errors.<ERP-code>` message is read through `useErrorText(featureErrors)`, which
  // builds the key from the code (`src/lib/errors/error-messages.ts`): the feature names the CODE
  // (its `FeatureErrorCodes`), never the key, so the quoted code is the reference (FE-13, D-32).
  const errorCode = /^errors\.(ERP-[A-Z]+-\d{4})$/.exec(leafPath)?.[1];
  if (errorCode !== undefined && quoted(errorCode).test(code)) return true;
  const parts = leafPath.split('.');
  for (let i = parts.length - 1; i > 0; i -= 1) {
    if (dynamicNamespace(parts.slice(0, i).join('.')).test(code)) return true;
  }
  return false;
};

